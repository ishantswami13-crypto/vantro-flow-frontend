// Self-hosts the site's Google fonts. Downloads the latin and latin-ext woff2
// subsets into public/fonts and writes app/fonts.css with the same family
// names, so every existing font-family rule keeps working with no request to
// Google at runtime (one less render-blocking hop, no third-party font CDN).
// Run: node scripts/fetch-fonts.mjs
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const OUT_DIR = path.join(ROOT, "public/fonts");
const CSS_OUT = path.join(ROOT, "app/fonts.css");
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";
const KEEP = new Set(["latin", "latin-ext"]);

const FAMILIES = [
  "Plus+Jakarta+Sans:wght@400;500;600;700",
  "IBM+Plex+Mono:wght@400;500",
  "Newsreader:ital,opsz,wght@0,6..72,400;0,6..72,500;1,6..72,400",
  "Space+Grotesk:wght@400;500;600;700",
  "Hanken+Grotesk:wght@300;400;500;600;700",
  "JetBrains+Mono:wght@400;500",
];

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

await mkdir(OUT_DIR, { recursive: true });
let css = "/* Generated by scripts/fetch-fonts.mjs. Do not edit by hand. */\n";
const seen = new Map();

for (const fam of FAMILIES) {
  const res = await fetch(`https://fonts.googleapis.com/css2?family=${fam}&display=swap`, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${fam}: ${res.status}`);
  const text = await res.text();
  // Each block is preceded by a /* subset */ comment.
  const blocks = text.split(/\/\*\s*([a-z-]+)\s*\*\//).slice(1);
  for (let i = 0; i < blocks.length; i += 2) {
    const subset = blocks[i];
    const block = blocks[i + 1].trim();
    if (!KEEP.has(subset)) continue;
    const family = block.match(/font-family:\s*'([^']+)'/)[1];
    const style = block.match(/font-style:\s*(\w+)/)[1];
    const url = block.match(/url\((https:[^)]+)\)/)[1];
    // Variable fonts return one file for every weight; download each file once.
    let file = seen.get(url);
    if (!file) {
      // Stable names (preloaded by path): one file per family, style and subset,
      // plus the weight for static fonts that ship a file per weight.
      const weight = block.match(/font-weight:\s*(\d+)/)[1];
      file = `${slug(family)}-${style}-${subset}.woff2`;
      if ([...seen.values()].includes(file)) file = file.replace(".woff2", `-${weight}.woff2`);
      const bin = await fetch(url);
      if (!bin.ok) throw new Error(`${url}: ${bin.status}`);
      await writeFile(path.join(OUT_DIR, file), Buffer.from(await bin.arrayBuffer()));
      seen.set(url, file);
    }
    css += `/* ${subset} */\n` + block.replace(url, `/fonts/${file}`)+ "\n";
  }
}

await writeFile(CSS_OUT, css);
console.log(`Wrote ${seen.size} files and app/fonts.css`);
